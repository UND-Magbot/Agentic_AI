def _form_groups(groups) -> list[dict]:
    return [{"title": g, "note": OPTIONAL_NOTE.get(g, ""),
             "questions": [{"code": c, "question": form_question(c), "example": ex,
                            "required": QUESTIONS[c].required} for c, ex in qs]}
            for g, qs in groups]
